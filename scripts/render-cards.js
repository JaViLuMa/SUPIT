function mapDataToStrengthsCardSnippet(title, description) {
  return `
    <article class="card">
      <h3 class="card__title">${title}</h3>
      <p class="card__description">
        ${description}
      </p>
    </article>
  `;
}

function renderStrengthsCards() {
  const strengthsContainer = document.getElementById("strengths");

  STRENGTHS.forEach((strength) => {
    const card = mapDataToStrengthsCardSnippet(
      strength.title,
      strength.description
    );

    strengthsContainer.innerHTML += card;
  });
}

function mapDataToHistorySnippet(year, title, description) {
  return `
    <article class="card">
      <h3 class="card__title"><span class="card__year">${year}.</span> - ${title}</h3>
      <p class="card__description">
        ${description}
      </p>
    </article>
  `;
}

function renderHistoryCards() {
  const historyContainer = document.getElementById("history");

  HISTORY.forEach((event) => {
    const card = mapDataToHistorySnippet(
      event.year,
      event.title,
      event.description
    );

    historyContainer.innerHTML += card;
  });
}

function mapDataToPartnerSnippet(title, image) {
  return `
    <div class="partner">
      <h2 class="partner__title">
        ${title}
      </h2>
      <img src="${image}" class="partner__image" />
    </div>
  `;
}

function renderPartnerCards() {
  const partnersContainer = document.getElementById("partners");

  PARTNERS.forEach((partner) => {
    const card = mapDataToPartnerSnippet(partner.title, partner.image);
    partnersContainer.innerHTML += card;
  });
}

function mapDataToReachUsSnippet(icon, title, description) {
  return `
    <div class="reach_us__card__content">
      <div class="reach_us__card__content__header">
        <img
          src="${icon}"
          class="reach_us__card__content__icon"
        />
        <h4 class="reach_us__card__content__title">${title}</h4>
      </div>
      <p class="reach_us__card__content__description">${description}</p>
    </div>
  `;
}

function renderReachUsCards() {
  const reachUsContainer = document.getElementById("reach-us-cards");

  REACH_US.forEach((group) => {
    const content = group
      .map((item) =>
        mapDataToReachUsSnippet(item.icon, item.title, item.description)
      )
      .join("");

    reachUsContainer.innerHTML += `<div class="reach_us__card">${content}</div>`;
  });
}

document.addEventListener("DOMContentLoaded", () => {
  renderStrengthsCards();
  renderHistoryCards();
  renderPartnerCards();
  renderReachUsCards();
});
